def _create_insights() -> None:
    op.execute(
        """
        CREATE TABLE insights (
            id               uuid PRIMARY KEY,
            project_id       uuid NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
            kind             text NOT NULL CHECK (char_length(kind) BETWEEN 1 AND 64),
            severity         insight_severity NOT NULL,
            status           insight_status NOT NULL,
            fingerprint      text NOT NULL CHECK (fingerprint ~ '^[0-9a-f]{32}$'),
            title            text NOT NULL,
            summary          text NOT NULL,
            failure_layer    text NOT NULL CHECK (failure_layer IN
                ('client', 'request', 'agent', 'provider', 'platform', 'traffic')),
            certainty        text NOT NULL CHECK (certainty IN ('measured', 'inferred')),
            evidence         jsonb NOT NULL CHECK (jsonb_typeof(evidence) = 'object'),
            suggested_fix    text NOT NULL,
            verification     text NOT NULL,
            first_seen_at    timestamptz NOT NULL,
            last_seen_at     timestamptz NOT NULL,
            occurrences      integer NOT NULL CHECK (occurrences >= 1),
            resolved_at      timestamptz,
            muted_until      timestamptz,
            mute_reason      text CHECK (char_length(mute_reason) BETWEEN 1 AND 500),
            acknowledged_by  uuid REFERENCES users (id) ON DELETE SET NULL,
            acknowledged_at  timestamptz,
            CONSTRAINT insights_project_fingerprint_key UNIQUE (project_id, fingerprint),
            CONSTRAINT insights_seen_order CHECK (last_seen_at >= first_seen_at),
            CONSTRAINT insights_resolved_for_status
                CHECK ((status = 'resolved') = (resolved_at IS NOT NULL)),
            CONSTRAINT insights_muted_for_status
                CHECK ((status = 'muted') = (muted_until IS NOT NULL)),
            CONSTRAINT insights_mute_pair
                CHECK ((muted_until IS NULL) = (mute_reason IS NULL)),
            CONSTRAINT insights_acknowledged_pair
                CHECK (acknowledged_by IS NULL OR acknowledged_at IS NOT NULL),
            CONSTRAINT insights_acknowledged_for_status
                CHECK (status <> 'acknowledged' OR acknowledged_at IS NOT NULL),
            CONSTRAINT insights_open_unacknowledged
                CHECK (status <> 'open' OR acknowledged_at IS NULL)
        )
        """
    )
    op.execute(
        "CREATE INDEX insights_project_status_seen_idx "
        "ON insights (project_id, status, last_seen_at DESC, id DESC)"
    )
    op.execute(
        "CREATE INDEX insights_evidence_trace_ids_idx "
        "ON insights USING gin ((evidence -> 'trace_ids') jsonb_path_ops)"
    )
    op.execute(
        "CREATE INDEX insights_acknowledged_by_idx ON insights (acknowledged_by) "
        "WHERE acknowledged_by IS NOT NULL"
    )


def _create_detector_runs() -> None:
    op.execute(
        """
        CREATE TABLE detector_runs (
            id            uuid PRIMARY KEY,
            project_id    uuid NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
            detector      text NOT NULL CHECK (char_length(detector) BETWEEN 1 AND 64),
            window_start  timestamptz NOT NULL,
            window_end    timestamptz NOT NULL,
            findings      integer CHECK (findings >= 0),
            truncated     boolean NOT NULL DEFAULT false,
            duration_ms   integer NOT NULL CHECK (duration_ms >= 0),
            error         text CHECK (char_length(error) BETWEEN 1 AND 500),
            ran_at        timestamptz NOT NULL DEFAULT now(),
            CONSTRAINT detector_runs_window_order CHECK (window_end >= window_start),
            CONSTRAINT detector_runs_outcome CHECK ((findings IS NULL) = (error IS NOT NULL))
        )
        """
    )
    op.execute(
        "CREATE INDEX detector_runs_project_ran_idx ON detector_runs (project_id, ran_at DESC)"
    )


def _enable_row_level_security(table: str) -> None:
    op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
    op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
    op.execute(
        f"CREATE POLICY {table}_project_isolation ON {table} "
        f"USING ({PROJECT_EXPRESSION}) WITH CHECK ({PROJECT_EXPRESSION})"
    )
    op.execute(
        f"CREATE POLICY {table}_worker_bypass ON {table} "
        f"USING ({BYPASS_EXPRESSION}) WITH CHECK ({BYPASS_EXPRESSION})"
    )


def _set_audit_actions(actions: tuple[str, ...]) -> None:
    listed = ", ".join(f"'{action}'" for action in actions)
    op.execute("ALTER TABLE audit_events DROP CONSTRAINT audit_events_action_check")
    op.execute(
        "ALTER TABLE audit_events ADD CONSTRAINT audit_events_action_check "
        f"CHECK (action IN ({listed}))"
    )
