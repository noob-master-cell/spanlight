"""Add insights, detector runs and the project's insight channels, and allow the insight audit
actions.

Revision ID: 0402
Revises: 0401
Create Date: 2026-10-10

An insight is a problem the detectors found in a project's spans, with its cause and a fix. One
row per problem: a fingerprint (`app.insights.fingerprint`) names it, and every later detection
of the same problem updates that row (`app.insights.service.apply_findings`). `detector_runs`
records each detector's pass over a project, so a quiet page can be told apart from a detector
that failed or never ran.

Choices worth knowing about:

* The ids are UUIDv7 generated by the application, so the columns have no default. Both tables
  carry `project_id` and cascade from `projects`, so deleting a project deletes its insights
  and runs.
* `severity` and `status` are PostgreSQL enums, like the alert enums. Adding a value later is
  `ALTER TYPE ... ADD VALUE`.
* The copy (title, summary, suggested fix, verification, failure layer, certainty) is stored
  with the row, so an insight reads the same after the catalogue's wording changes. The layer
  and certainty CHECKs repeat the catalogue's vocabularies.
* `UNIQUE (project_id, fingerprint)` is the conflict target of the upsert that applies a batch
  of findings. Its index leads with `project_id`, so it also serves the foreign key.
* The status decides which columns are set, and the CHECKs hold that: `resolved_at` exactly
  when resolved, `muted_until` exactly when muted, a mute reason exactly with a mute end, an
  acknowledgement whenever the status is `acknowledged` and never while it is `open` (a reopened
  insight starts unacknowledged). `acknowledged_by` is `ON DELETE SET NULL`: removing a person
  keeps the acknowledgement time. Its index is partial, since most insights are never
  acknowledged, and keeps deleting a user from scanning the table.
* `(project_id, status, last_seen_at DESC, id DESC)` serves the list's keyset order, the status
  filter and the auto-resolve pass. The GIN index on `evidence -> 'trace_ids'` (`jsonb_path_ops`)
  answers "which insights cite this trace" for the trace page.
* `detector_runs.findings` is NULL exactly when the run failed (`error` is set): a detector that
  raised found an unknown number of problems, not zero. `(project_id, ran_at DESC)` serves the
  runs list and the stale-first project order of the detector job.
* `projects.insight_channel_ids` names the alert channels that hear about critical insights. It
  is an array without foreign keys, like `alert_rules.channel_ids`: channels belong to the
  organization, a channel can be deleted while a project still names it, and notifying skips an
  id that no longer resolves. At most 10, by CHECK. The constant default is stored in the
  catalogue, so adding the column rewrites no rows.
* Row-level security on both new tables is the policy pair every project-scoped table has, in
  the InitPlan form of 0017.

`audit_events.action` is a CHECK over a fixed list, so it is dropped and added again with every
action allowed so far plus the insight actions, as in 0301. `projects` and `audit_events` are
locked briefly; the wait for each lock is capped at 5 seconds (`SET LOCAL lock_timeout`, as in
0301 and 0305), so a long transaction fails the migration instead of queueing every request
behind it. If it times out, run it again.

Downgrade deletes the audit events that use the insight actions, which the older constraint
would reject, restores the previous list, drops the column, the tables and their types. The
insights and their history are gone with them.
"""

